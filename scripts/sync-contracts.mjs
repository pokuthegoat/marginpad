// Copies what the frontend needs out of the Foundry project:
//   - ABIs from contracts/out            -> src/chain/abis.ts
//   - deployments/<chainId>.json         -> src/chain/deployments.json (Robinhood testnet, committed)
//                                           src/chain/deployments.local.json (local Anvil, git-ignored)
// Run after `npm run contracts:build` and after every deployment:  npm run contracts:sync
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const out = path.join(root, 'contracts/out')
const dest = path.join(root, 'src/chain')

const names = { MarginPool: 'marginPoolAbi', MarginTrading: 'marginTradingAbi', RiskManager: 'riskManagerAbi', OwnerPriceOracle: 'priceOracleAbi' }
let abis = '// GENERATED by scripts/sync-contracts.mjs from contracts/out. Do not edit by hand.\n'
for (const [contract, exportName] of Object.entries(names)) {
  const file = path.join(out, `${contract}.sol`, `${contract}.json`)
  if (!fs.existsSync(file)) throw new Error(`Missing ${file}. Run "npm run contracts:build" first.`)
  const { abi } = JSON.parse(fs.readFileSync(file, 'utf8'))
  abis += `\nexport const ${exportName} = ${JSON.stringify(abi)} as const\n`
}
fs.writeFileSync(path.join(dest, 'abis.ts'), abis)

// First block of a deployment (needed to scan event logs). Foundry records it in the broadcast receipts.
function deployBlock(chainId) {
  const file = path.join(root, `contracts/broadcast/Deploy.s.sol/${chainId}/run-latest.json`)
  if (!fs.existsSync(file)) return 0
  const run = JSON.parse(fs.readFileSync(file, 'utf8'))
  const blocks = (run.receipts ?? []).map((r) => Number(BigInt(r.blockNumber)))
  return blocks.length ? Math.min(...blocks) : 0
}

const targets = { 46630: 'deployments.json', 31337: 'deployments.local.json' }
for (const [chainId, fileName] of Object.entries(targets)) {
  const src = path.join(root, `contracts/deployments/${chainId}.json`)
  if (!fs.existsSync(src)) {
    if (chainId === '46630' && !fs.existsSync(path.join(dest, fileName))) fs.writeFileSync(path.join(dest, fileName), '{}\n')
    continue
  }
  const d = JSON.parse(fs.readFileSync(src, 'utf8'))
  d.deployBlock = deployBlock(chainId)
  fs.writeFileSync(path.join(dest, fileName), JSON.stringify(d, null, 2) + '\n')
  console.log(`synced ${fileName} (chain ${chainId}, deploy block ${d.deployBlock})`)
}
console.log('synced src/chain/abis.ts')
